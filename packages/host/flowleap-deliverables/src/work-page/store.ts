/**
 * The office action work pages: the `<report>.work.json` file that a structured `office-action-scaffold` save writes
 * beside the report, the index of those files by chat, and the attorney's changes of the review fields. A save writes
 * the findings of its `officeAction` input and keeps the review fields of each objection whose id, ground and title
 * are unchanged; it names the review fields that it could not keep. A review change reads the file, replaces the review
 * fields of one objection, and writes the file again; it never changes the findings. Each write validates the whole
 * file first. The changes of one file run one after another, so a save and a review change never lose each other's
 * write. The model sees the review fields only when it reads the file with a tool, which the Session log records.
 * @module
 */

import { createHash } from 'node:crypto'
import { basename } from 'node:path'
import { z } from 'zod'
import { brandString } from '@deepseek-ai/dsh-brand'
import { FsError, type FileSystem } from '@deepseek-ai/dsh-fs'
import { SessionId } from '@deepseek-ai/dsh-session/types'
import { defineDomain, domainTable, type KvTable } from '@deepseek-ai/dsh-storage-domain'
import { RemoteError } from '@deepseek-ai/dsh-typert-protocol'
import { officeActionSchema } from './office-action-input.ts'
import {
  MAX_NOTE_LENGTH, MAX_OWNER_LENGTH, NEW_REVIEW, REVIEW_STATES,
  type OfficeActionFindings, type ReviewEntry, type WorkPageFile, type WorkPageId, type WorkPageReviewRequest,
  type WorkPageSummary, type WorkPageView,
} from './types.ts'

declare module '@deepseek-ai/dsh-typert-protocol' {
  interface RemoteErrorDetailsMap {
    /** No work page that the caller may see has this id. */
    'flowleap-work-pages/not-found': { readonly id: string }
    /** The work page has no objection with this id. */
    'flowleap-work-pages/objection-not-found': { readonly id: string; readonly objection: string }
    /** The work page file is missing or is not a valid work page file. */
    'flowleap-work-pages/unreadable': { readonly id: string; readonly reason: string }
  }
}

/**
 * The work page file beside a report: a stable name, replaced by each save of the report.
 * @param reportPath - the report path.
 * @returns the work page file path.
 */
export function workPagePath(reportPath: string): string {
  return `${reportPath}.work.json`
}

/** A work page id: the first 16 hex digits of the SHA-256 of the work page file's process path. */
export const workPageIdSchema = z.string().regex(/^[0-9a-f]{16}$/).transform(value => brandString<WorkPageId>(value))

/**
 * The id of the work page at one path.
 * @param path - the process path of the work page file.
 * @returns the id.
 */
export function workPageId(path: string): WorkPageId {
  return brandString<WorkPageId>(createHash('sha256').update(path).digest('hex').slice(0, 16))
}

/**
 * The text for a reader of the file.
 * @param report - the report file name.
 * @returns one sentence.
 */
export function aboutText(report: string): string {
  const states = `${REVIEW_STATES.slice(0, -1).join(', ')} or ${REVIEW_STATES[REVIEW_STATES.length - 1]}`
  return `The findings come from ${report} and change only when that report is saved again. "review" holds, for each objection id, the state (${states}), the owner and the note that the attorney set on the office action board. Do not edit this file.`
}

const reviewEntrySchema = z.strictObject({
  state: z.enum(REVIEW_STATES),
  owner: z.string().max(MAX_OWNER_LENGTH),
  note: z.string().max(MAX_NOTE_LENGTH),
  ground: z.string(),
  title: z.string(),
}) satisfies z.ZodType<ReviewEntry>

/** The work page file: the shape of each write and of each read back from disk. */
export const workPageFileSchema = z.strictObject({
  schemaVersion: z.literal(1),
  kind: z.literal('office-action'),
  about: z.string(),
  report: z.string(),
  findings: officeActionSchema,
  review: z.record(z.string(), reviewEntrySchema),
}).superRefine((file, check) => {
  const ids = file.findings.objections.map(objection => objection.id)
  const keys = Object.keys(file.review)
  if (keys.length !== ids.length || ids.some(id => !Object.hasOwn(file.review, id))) {
    check.addIssue({ code: 'custom', path: ['review'], message: `the review keys must equal the objection ids (${ids.join(', ')})` })
    return
  }
  for (const objection of file.findings.objections) {
    const entry = file.review[objection.id]
    if (entry.ground !== objection.ground || entry.title !== objection.title) {
      check.addIssue({ code: 'custom', path: ['review', objection.id], message: 'the ground and the title must equal those of the objection' })
    }
  }
}) satisfies z.ZodType<WorkPageFile>

/** One indexed work page: where its file is and which chat wrote it. */
const entrySchema = z.strictObject({
  /** Process path of the work page file. */
  path: z.string().min(1),
  /** The report path as the save named it. */
  report: z.string().min(1),
  sessionId: z.string().min(1).transform(value => SessionId(value)),
  /** RFC 3339 UTC time of the save that wrote the page. */
  savedAt: z.iso.datetime(),
})

/** Stored index entry. */
export type WorkPageEntry = z.infer<typeof entrySchema>

/** The `flowleap_work_pages` domain: one entry per work page id. */
export const workPagesDomainSpec = defineDomain({
  name: 'flowleap_work_pages',
  version: 1,
  tables: { pages: domainTable<WorkPageId, WorkPageEntry>(entrySchema) },
})

/** The index table: the storage table when storage is mounted, else a table in memory. */
export type WorkPageIndex = Pick<KvTable<WorkPageId, WorkPageEntry>, 'get' | 'entries' | 'put'>

/**
 * An index table in memory, for a composition without storage.
 * @returns the table.
 */
export function memoryIndex(): WorkPageIndex {
  const rows = new Map<WorkPageId, WorkPageEntry>()
  return {
    get: id => rows.get(id),
    entries: () => rows.entries(),
    put: (id, entry) => {
      rows.set(id, entry)
      return Promise.resolve()
    },
  }
}

/** The part of the filesystem contract the work pages use. */
export type WorkPageFileSystem = Pick<FileSystem, 'resolve' | 'readText' | 'writeText'>

/** One structured save of an office action analysis, as the writer gives it. */
export interface WorkPageSave {
  /** Process path of the saved report. */
  readonly reportPath: string
  /** The report path as the save named it. */
  readonly displayPath: string
  /** The valid `officeAction` input of the save. */
  readonly findings: OfficeActionFindings
  /** The chat that saved the report. */
  readonly sessionId: SessionId
  readonly signal?: AbortSignal
}

/** What a save wrote. */
export interface WorkPageSaveResult {
  /** Process path of the work page file. */
  readonly path: string
  /** The lines that the save result gives the model. */
  readonly text: string
}

/** The previous file of a save: none, a valid file, or a file that the save could not use, with where it was kept. */
type Previous =
  | { readonly kind: 'none' }
  | { readonly kind: 'file'; readonly file: WorkPageFile }
  | { readonly kind: 'unusable'; readonly reason: string; readonly kept: string }

/**
 * The work pages of this Host. Every write of one page file runs in that page's queue.
 */
export class WorkPages {
  private index: WorkPageIndex = memoryIndex()
  private readonly queues = new Map<WorkPageId, Promise<unknown>>()

  /**
   * @param fs - the filesystem the files are read and written through.
   * @param changed - called with the page after each committed save or review change.
   * @param now - the clock of the index entry's `savedAt` and of a kept file's name; a test passes its own.
   */
  constructor(
    private readonly fs: WorkPageFileSystem,
    private readonly changed: (view: WorkPageView) => void,
    private readonly now: () => Date = () => new Date(),
  ) {}

  /**
   * Use a storage table as the index; the entries in memory are copied into it.
   * @param table - the table, or `undefined` to go back to an index in memory.
   */
  async attach(table: WorkPageIndex | undefined): Promise<void> {
    const previous = this.index
    this.index = table ?? memoryIndex()
    if (table === undefined) return
    for (const [id, entry] of previous.entries()) {
      if (table.get(id) === undefined) await table.put(id, entry)
    }
  }

  /**
   * Write the work page of a structured office action save. The review fields of an objection stay when the previous
   * file has an objection with the same id, ground and title.
   * @param save - the saved report and its findings.
   * @returns the work page file path and the lines for the save result.
   * @throws when the previous file cannot be read for a reason other than its absence, or the write fails.
   */
  async save(save: WorkPageSave): Promise<WorkPageSaveResult> {
    const path = workPagePath(save.reportPath)
    const id = workPageId(path)
    const display = workPagePath(save.displayPath)
    const { view, notes } = await this.serialize(id, async () => {
      const previous = await this.previous(save.reportPath, path, save.signal)
      const report = basename(save.reportPath)
      const { review, notes } = mergeReview(save.findings, previous)
      const file = workPageFileSchema.parse({ schemaVersion: 1, kind: 'office-action', about: aboutText(report), report, findings: save.findings, review })
      await this.fs.writeText(await this.fs.resolve(path, signalOption(save.signal)), serialized(file), undefined, save.signal)
      const entry: WorkPageEntry = { path, report: save.displayPath, sessionId: save.sessionId, savedAt: this.now().toISOString() }
      await this.index.put(id, entry)
      return { view: { summary: summaryOf(id, entry, file), file }, notes }
    })
    this.changed(view)
    const count = save.findings.objections.length
    return {
      path,
      text: [
        `Work page: ${display} holds the ${String(count)} objection${count === 1 ? '' : 's'} of this analysis for the office action board, where the attorney sets a review state, an owner and a note on each objection. Read that file before you revise this analysis or write its response plan; do not edit it.`,
        ...notes,
      ].join('\n'),
    }
  }

  /**
   * Every listed work page whose file is readable, newest save first.
   * @param visible - whether the caller may see the chat that wrote a page.
   * @returns the summaries.
   */
  async list(visible: (sessionId: SessionId) => boolean): Promise<WorkPageSummary[]> {
    const views = await Promise.all([...this.index.entries()]
      .filter(([, entry]) => visible(entry.sessionId))
      // A page whose file was moved, deleted or damaged is left out; `read` names the cause.
      .map(([id, entry]) => this.view(id, entry).catch((_error: unknown) => undefined)))
    return views.flatMap(view => view === undefined ? [] : [view.summary])
      .sort((left, right) => right.savedAt.localeCompare(left.savedAt))
  }

  /**
   * One work page with its file.
   * @param id - the page.
   * @param visible - whether the caller may see the chat that wrote a page.
   * @returns the view.
   * @throws RemoteError `flowleap-work-pages/not-found` or `flowleap-work-pages/unreadable`.
   */
  async read(id: WorkPageId, visible: (sessionId: SessionId) => boolean): Promise<WorkPageView> {
    return this.view(id, this.entry(id, visible))
  }

  /**
   * Change the review fields of one objection.
   * @param request - the page, the objection, and the fields to change.
   * @param visible - whether the caller may see the chat that wrote a page.
   * @returns the page after the change.
   * @throws RemoteError `flowleap-work-pages/not-found`, `flowleap-work-pages/objection-not-found` or
   * `flowleap-work-pages/unreadable`.
   */
  async review(request: WorkPageReviewRequest, visible: (sessionId: SessionId) => boolean): Promise<WorkPageView> {
    const entry = this.entry(request.id, visible)
    const view = await this.serialize(request.id, async () => {
      const file = await this.readOrThrow(request.id, entry.path)
      const current = Object.hasOwn(file.review, request.objection) ? file.review[request.objection] : undefined
      if (current === undefined) {
        throw new RemoteError('flowleap-work-pages/objection-not-found', `the work page has no objection "${request.objection}"`,
          { id: request.id, objection: request.objection })
      }
      const next: ReviewEntry = {
        ...current,
        state: request.state ?? current.state,
        owner: request.owner ?? current.owner,
        note: request.note ?? current.note,
      }
      const changed = workPageFileSchema.parse({ ...file, review: { ...file.review, [request.objection]: next } })
      await this.fs.writeText(await this.fs.resolve(entry.path), serialized(changed))
      return { summary: summaryOf(request.id, entry, changed), file: changed }
    })
    this.changed(view)
    return view
  }

  /**
   * The previous file of a save. Only a missing file is no previous file. A file that is not a valid work page file is
   * copied to `<report>.work.<time>.json` before the save replaces it.
   * @throws when the file exists but cannot be read; the save then writes nothing, and the file keeps its review fields.
   */
  private async previous(reportPath: string, path: string, signal: AbortSignal | undefined): Promise<Previous> {
    let text: string
    try {
      text = await this.fs.readText(await this.fs.resolve(path, signalOption(signal)), signal)
    } catch (error: unknown) {
      if (error instanceof FsError && error.code === 'FS_NOT_FOUND') return { kind: 'none' }
      const reason = error instanceof FsError ? error.code : error instanceof Error ? error.message : String(error)
      throw new Error(`the previous work page file cannot be read (${reason}), so it stays as it is with its review fields`, { cause: error })
    }
    try {
      return { kind: 'file', file: workPageFileSchema.parse(JSON.parse(text)) }
    } catch (error: unknown) {
      const kept = `${reportPath}.work.${this.now().toISOString().replace(/[:.]/g, '-')}.json`
      await this.fs.writeText(await this.fs.resolve(kept, signalOption(signal)), text, undefined, signal)
      return { kind: 'unusable', reason: error instanceof z.ZodError ? 'it is not a valid work page file' : 'it is not JSON', kept }
    }
  }

  private entry(id: WorkPageId, visible: (sessionId: SessionId) => boolean): WorkPageEntry {
    const entry = this.index.get(id)
    if (entry === undefined || !visible(entry.sessionId)) {
      throw new RemoteError('flowleap-work-pages/not-found', `no work page "${id}"`, { id })
    }
    return entry
  }

  private async view(id: WorkPageId, entry: WorkPageEntry): Promise<WorkPageView> {
    const file = await this.readOrThrow(id, entry.path)
    return { summary: summaryOf(id, entry, file), file }
  }

  private async readOrThrow(id: WorkPageId, path: string): Promise<WorkPageFile> {
    try {
      return workPageFileSchema.parse(JSON.parse(await this.fs.readText(await this.fs.resolve(path))))
    } catch (error: unknown) {
      const reason = error instanceof FsError ? error.code : error instanceof z.ZodError ? 'not a valid work page file' : String(error)
      throw new RemoteError('flowleap-work-pages/unreadable', `the work page file ${path} cannot be read: ${reason}`, { id, reason }, { cause: error })
    }
  }

  private serialize<T>(id: WorkPageId, work: () => Promise<T>): Promise<T> {
    const pending = (this.queues.get(id) ?? Promise.resolve()).then(work)
    // The caller receives the failure; the next change of the page still runs.
    const settled = pending.catch(() => undefined)
    this.queues.set(id, settled)
    void settled.then(() => { if (this.queues.get(id) === settled) this.queues.delete(id) })
    return pending
  }
}

/**
 * The review fields of a new save, and the lines that name the review fields it could not keep. An entry stays with
 * the objection of the same id, ground and title; it never moves to another objection.
 */
function mergeReview(findings: OfficeActionFindings, previous: Previous): { review: Record<string, ReviewEntry>; notes: string[] } {
  const old = previous.kind === 'file' ? previous.file.review : {}
  const review: Record<string, ReviewEntry> = {}
  for (const objection of findings.objections) {
    const entry = Object.hasOwn(old, objection.id) ? old[objection.id] : undefined
    const same = entry !== undefined && entry.ground === objection.ground && entry.title === objection.title
    review[objection.id] = same ? entry : { ...NEW_REVIEW, ground: objection.ground, title: objection.title }
  }
  const lost = Object.entries(old).filter(([id, entry]) => review[id] !== entry && isSet(entry))
  const notes = lost.map(([id, entry]) => {
    const now = findings.objections.find(objection => objection.ground === entry.ground && objection.title === entry.title)
    const where = now === undefined
      ? 'no objection of this save has its ground and title'
      : `objection ${now.id} of this save has its ground and title, but review fields never move to another objection`
    return `Review fields not kept: objection ${id} ("${entry.title}", ${entry.ground}) was ${entry.state} with owner "${entry.owner}" and note "${entry.note}"; ${where}. Tell the attorney to set them again on the board.`
  })
  if (previous.kind === 'unusable') {
    notes.push(`Review fields not kept: the previous work page file could not be used because ${previous.reason}; it is kept as ${basename(previous.kept)}. Tell the attorney.`)
  }
  return { review, notes }
}

/** Whether the attorney changed an entry from the new state. */
function isSet(entry: ReviewEntry): boolean {
  return entry.state !== NEW_REVIEW.state || entry.owner !== NEW_REVIEW.owner || entry.note !== NEW_REVIEW.note
}

function signalOption(signal: AbortSignal | undefined): { signal?: AbortSignal } {
  return signal === undefined ? {} : { signal }
}

function serialized(file: WorkPageFile): string {
  return `${JSON.stringify(file, null, 2)}\n`
}

function summaryOf(id: WorkPageId, entry: WorkPageEntry, file: WorkPageFile): WorkPageSummary {
  return {
    id,
    sessionId: entry.sessionId,
    report: entry.report,
    path: workPagePath(entry.report),
    application: file.findings.application,
    communication: file.findings.communication,
    savedAt: entry.savedAt,
    objections: file.findings.objections.length,
    needsReview: Object.values(file.review).filter(fields => fields.state === 'needs_review').length,
  }
}
