/**
 * The work page of a structured `office-action-scaffold` save over the real local filesystem: the report rendered
 * from `officeAction`, the `<report>.work.json` file beside it, the review fields that a later save keeps or names, and
 * the previous files that a save cannot use.
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { SessionId } from '@deepseek-ai/dsh-session'
import { DeliveredPaths, officeActionTemplateSave, type WorkPageFile } from '../src/index.ts'
import { FINDINGS, OFFICE_ACTION, PLAN, structuredSave, withObjection } from './work-page-fixtures.ts'
import { writerBench } from './writer-test-bench.ts'

const NEW = { state: 'needs_review', owner: '', note: '' }

describe('structured office action save', () => {
  const cleanups: (() => Promise<unknown>)[] = []
  afterEach(async () => {
    for (const cleanup of cleanups.splice(0)) await cleanup()
  })

  async function bench() {
    const bench = await writerBench()
    cleanups.push(bench.dispose)
    bench.ctx.provide('remoteAccess', { allows: () => true } as never)
    await vi.waitFor(() => { expect(bench.ctx.get('flowleapWorkPages')).toBeDefined() })
    const path = join(bench.dir, `${OFFICE_ACTION}.work.json`)
    const fileOf = async (): Promise<WorkPageFile> => JSON.parse(await readFile(path, 'utf8')) as WorkPageFile
    const idOf = async () => (await bench.ctx.flowleapWorkPages.list())[0]!.id
    return { ...bench, pages: bench.ctx.flowleapWorkPages, path, fileOf, idOf }
  }

  it('renders the report from officeAction and writes the work page beside it', async () => {
    const { write, dir, fileOf } = await bench()
    const text = await write(structuredSave())
    expect(text).toContain(`Work page: ${OFFICE_ACTION}.work.json holds the 2 objections of this analysis for the office action board, where the attorney sets a review state, an owner and a note on each objection. Read that file before you revise this analysis or write its response plan; do not edit it.`)
    expect(text.trimEnd().endsWith('Delivered to the user; do not call `present` for these files.')).toBe(true)
    const report = await readFile(join(dir, OFFICE_ACTION), 'utf8')
    expect(report).toContain('# Office Action Response')
    expect(report).toContain('### Objection 1.2: Clarity of claim 9')
    expect(report).toContain('## 4. Response plan')
    expect(report.indexOf('## 3. Claim-by-claim comparison')).toBeLessThan(report.indexOf('## 4. Response plan'))
    const file = await fileOf()
    expect(file).toMatchObject({ schemaVersion: 1, kind: 'office-action', report: '2026-09-30-analysis.md', findings: FINDINGS })
    expect(file.about).toBe('The findings come from 2026-09-30-analysis.md and change only when that report is saved again. "review" holds, for each objection id, the state (needs_review, relevant, done or not_relevant), the owner and the note that the attorney set on the office action board. Do not edit this file.')
    expect(file.review).toEqual({
      '1': { ...NEW, ground: 'Art. 54 EPC', title: 'Claims 1-7 lack novelty over D1' },
      '1.2': { ...NEW, ground: 'Art. 84 EPC', title: 'Clarity of claim 9' },
    })
  })

  it('refuses invalid fields before any file is written', async () => {
    const { write, dir } = await bench()
    const text = await write(structuredSave({ ...FINDINGS, deadline: '2026-02-30' }))
    expect(text).toBe('Report was not saved. Correct these fields of officeAction and save again:\n- officeAction.deadline: a real calendar date as YYYY-MM-DD, or null')
    await expect(readdir(dir)).resolves.toEqual([])
  })

  it('keeps the review fields of an objection with the same id, ground and title, and names the fields it drops', async () => {
    const { write, pages, fileOf, idOf } = await bench()
    await write(structuredSave())
    const id = await idOf()
    await pages.review({ id, objection: '1', state: 'relevant', owner: 'M. Keller', note: 'Argue.' })
    await pages.review({ id, objection: '1.2', state: 'done' })
    await write(structuredSave(withObjection(1, { legalBasis: 'Art. 84 EPC, second sentence' })))
    expect((await fileOf()).review).toEqual({
      '1': { state: 'relevant', owner: 'M. Keller', note: 'Argue.', ground: 'Art. 54 EPC', title: 'Claims 1-7 lack novelty over D1' },
      '1.2': { state: 'done', owner: '', note: '', ground: 'Art. 84 EPC', title: 'Clarity of claim 9' },
    })
    const changed = await write(structuredSave(withObjection(0, { ground: 'Art. 56 EPC' })))
    expect(changed).toContain('Review fields not kept: objection 1 ("Claims 1-7 lack novelty over D1", Art. 54 EPC) was relevant with owner "M. Keller" and note "Argue."; no objection of this save has its ground and title. Tell the attorney to set them again on the board.')
    expect((await fileOf()).review['1']).toEqual({ ...NEW, ground: 'Art. 56 EPC', title: 'Claims 1-7 lack novelty over D1' })
    expect((await fileOf()).review['1.2']).toMatchObject({ state: 'done' })
    const moved = await write(structuredSave({ ...FINDINGS, objections: [FINDINGS.objections[0], { ...FINDINGS.objections[1]!, id: '2' }] }))
    expect(moved).toContain('Review fields not kept: objection 1.2 ("Clarity of claim 9", Art. 84 EPC) was done with owner "" and note ""; objection 2 of this save has its ground and title, but review fields never move to another objection.')
    expect((await fileOf()).review['2']).toEqual({ ...NEW, ground: 'Art. 84 EPC', title: 'Clarity of claim 9' })
  })

  it('keeps a previous file that is not a valid work page file and says that its review fields are not kept', async () => {
    const { write, path, dir, fileOf } = await bench()
    await mkdir(join(dir, 'office-actions/EP4814394'), { recursive: true })
    await writeFile(path, 'not json')
    const text = await write(structuredSave())
    const kept = (await readdir(join(dir, 'office-actions/EP4814394'))).filter(name => /^2026-09-30-analysis\.md\.work\..+\.json$/.test(name) && !name.endsWith('.md.work.json'))
    expect(kept).toHaveLength(1)
    expect(await readFile(join(dir, 'office-actions/EP4814394', kept[0]!), 'utf8')).toBe('not json')
    expect(text).toContain(`Review fields not kept: the previous work page file could not be used because it is not JSON; it is kept as ${kept[0]!}. Tell the attorney.`)
    expect((await fileOf()).review['1']).toMatchObject(NEW)
    await writeFile(path, '{"schemaVersion":2}')
    expect(await write(structuredSave())).toContain('could not be used because it is not a valid work page file')
  })

  it('writes nothing over a previous file that cannot be read, and keeps the report', async () => {
    const { write, dir, logged } = await bench()
    await mkdir(join(dir, `${OFFICE_ACTION}.work.json`), { recursive: true })
    const text = await write(structuredSave())
    expect(text).toMatch(/Work page: not written, because the previous work page file cannot be read \(.+\), so it stays as it is/)
    expect(text).toContain('The office action board does not show the findings of this save. Tell the attorney.')
    expect(await readFile(join(dir, OFFICE_ACTION), 'utf8')).toContain('### Objection 1: Claims 1-7 lack novelty over D1')
    expect(logged.some(line => line.includes(`work page of ${OFFICE_ACTION} was not written`))).toBe(true)
  })

  it('names a save without officeAction or without a chat, and leaves other templates alone', async () => {
    const { write, dir } = await bench()
    const plan = await write({ filePath: 'office-actions/x/plan.md', content: PLAN, template: 'office-action-scaffold' })
    expect(plan).toContain('Work page: none, because this save has no officeAction. The office action board shows only an analysis that is saved with officeAction.')
    const loose = await write(structuredSave(FINDINGS, 'office-actions/x/loose.md'), false)
    expect(loose).toContain('Work page: not written, because this save has no chat. The office action board shows only an analysis that a chat saved.')
    await expect(readFile(join(dir, 'office-actions/x/loose.md.work.json'), 'utf8')).rejects.toThrow()
    const memo = await write({ filePath: 'memo.md', content: PLAN, template: 'patentability-opinion', matter: 'EP4814394' })
    expect(memo).not.toContain('Work page:')
  })
})

describe('office action template save', () => {
  it('marks the work page as delivered in the chat that saved it', async () => {
    const delivered = new DeliveredPaths()
    const save = vi.fn(() => Promise.resolve({ path: '/w/a.md.work.json', text: 'Work page: a.md.work.json' }))
    const template = officeActionTemplateSave({ workPages: { save } as never, delivered, warn: () => {} })
    const prepared = template.prepare({ filePath: 'a.md', content: PLAN, officeAction: FINDINGS })
    if (prepared.kind !== 'ready') throw new Error('expected a prepared save')
    const chat = SessionId('chat')
    const text = await prepared.afterSave({ reportPath: '/w/a.md', displayPath: 'a.md', sessionId: chat, signal: new AbortController().signal })
    expect(text).toBe('Work page: a.md.work.json')
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ reportPath: '/w/a.md', displayPath: 'a.md', findings: FINDINGS, sessionId: chat }))
    expect(delivered.has(chat, '/w/a.md.work.json')).toBe(true)
  })

  it('reports a failure that is not an Error', async () => {
    const warned: string[] = []
    // oxlint-disable-next-line typescript/prefer-promise-reject-errors -- a failure that is not an Error is the case under test
    const template = officeActionTemplateSave({ workPages: { save: () => Promise.reject('EBUSY') } as never, warn: (line) => { warned.push(line) } })
    const prepared = template.prepare({ filePath: 'a.md', content: PLAN, officeAction: FINDINGS })
    if (prepared.kind !== 'ready') throw new Error('expected a prepared save')
    const text = await prepared.afterSave({ reportPath: '/w/a.md', displayPath: 'a.md', sessionId: SessionId('chat'), signal: new AbortController().signal })
    expect(text).toBe('Work page: not written, because EBUSY. The office action board does not show the findings of this save. Tell the attorney.')
    expect(warned).toEqual(['flowleap-deliverables: work page of a.md was not written: EBUSY'])
  })
})
